def _request_hash(req: ExplanationRequest) -> str:
    """
    Deterministic hash of the request payload.
    Two requests with identical data produce the same hash → cache hit.
    """
    payload = req.model_dump(exclude={"additional_context"})
    serialised = json.dumps(payload, sort_keys=True, default=str)
    return hashlib.sha256(serialised.encode()).hexdigest()[:16]


def _load_cached(
    db: Session,
    iso3: str,
    period: str,
    data_hash: str,
) -> AiExplanation | None:
    return (
        db.query(AiExplanation)
        .filter(
            AiExplanation.country_id        == iso3,
            AiExplanation.explanation_type  == "snapshot_v2",
            AiExplanation.year              == _period_year(period),
        )
        .order_by(AiExplanation.generated_at.desc())
        .first()
    )


def _period_year(period: str) -> int:
    """Extract the year from a period string like 'Q2 2026' or '2025'."""
    import re
    match = re.search(r"\b(20\d{2})\b", period)
    return int(match.group(1)) if match else datetime.now().year


def _save_to_db(
    db: Session,
    req: ExplanationRequest,
    resp: ExplanationResponse,
    data_hash: str,
) -> None:
    """Persist the explanation to the ai_explanations table."""
    try:
        row = AiExplanation(
            country_id       = req.country_iso3,
            explanation_type = "snapshot_v2",
            year             = _period_year(req.period),
            explanation_text = resp.short_summary,
            # Store full JSON in the text field for now; V2 can add dedicated columns
            # You can add a JSONB column to ai_explanations if needed
        )
        db.add(row)
        db.commit()
    except Exception as e:
        logger.warning("Could not save explanation to DB: %s", e)
        db.rollback()


