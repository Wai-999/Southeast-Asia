# POST /explain/  — main endpoint
# ─────────────────────────────────────────────────────────────────────────────

@router.post(
    "/",
    response_model  = ExplanationResponse,
    summary         = "Generate AI explanation for a country economic snapshot",
    description     = (
        "Accepts a full set of economic indicators, active pattern alerts, and news signals. "
        "Returns a structured 6-section AI explanation generated by Claude. "
        "Responses are cached by data hash — identical inputs return instantly. "
        "Falls back gracefully if Claude is unavailable."
    ),
)
def explain_snapshot(
    req: ExplanationRequest,
    db: Session = Depends(get_db),
) -> ExplanationResponse:

    logger.info("POST /explain/ — %s / %s", req.country_iso3, req.period)

    # Minimum data check — refuse if no indicator data at all
    indicators = [
        req.gdp_growth, req.inflation, req.exports, req.imports,
        req.exchange_rate, req.fdi, req.public_debt,
    ]
    if all(ind is None for ind in indicators):
        raise HTTPException(
            status_code = status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail = (
                "At least one economic indicator is required. "
                "Provide gdp_growth, inflation, exports, or any other indicator."
            ),
        )

    # Generate explanation (handles all errors internally, returns fallback if needed)
    response = generate_explanation(req)

    # Persist (best-effort — don't fail the request if DB is unavailable)
    data_hash = _request_hash(req)
    _save_to_db(db, req, response, data_hash)

    return response


